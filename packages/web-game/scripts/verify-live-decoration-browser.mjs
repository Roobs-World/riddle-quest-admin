import {openSolarGame} from './solar-browser-fixture.mjs';
import path from 'node:path';

// Uses the solar fixture's actual frame, hosted authority, Three resources and controlled graphics driver.
export async function verifyLiveDecoration({page,width,url,baseline,metric,output,scheduler}) {
 const value=field=>page.evaluate(field=>window.probe[field],field);
 const pending=()=>page.evaluate(()=>window.pendingFrames());
 const idle=()=>page.evaluate(()=>window.pendingIdle());
 const draft=()=>page.evaluate(()=>window.probe.saves.findLast(row=>row.activeGame)?.activeGame.currentLetters.join('').toUpperCase());
 const token=()=>page.evaluate(()=>window.probe.saves.findLast(row=>row.activeGame)?.activeGame.sessionToken);
 const settle=()=>page.waitForTimeout(100);
 const motion=async(value,platform=false)=>{await page.evaluate(({value,platform})=>platform?window.applyMotion(value):window.setMotion(value),{value,platform});await settle();};
 const start=async(query='')=>{await openSolarGame(page,url+'?custom=1&harness=race'+(scheduler==='timer'?'&timer=1':'')+query);
  await page.keyboard.type('pian');await page.waitForFunction(()=>window.probe.saves.some(row=>row.activeGame?.currentLetters.join('').toUpperCase()==='PIAN'));
  await page.evaluate(()=>window.controlFrames());await settle();};
 const mount=async()=>{await page.evaluate(()=>window.releaseScene());await page.locator('.solar-system canvas').waitFor({state:'attached'});
  await page.waitForFunction(()=>window.probe.observers.some(row=>row.active));await page.evaluate(width=>{window.resizeScene(width,844);window.step();},width);};
 const openRace=async()=>{await page.getByRole('button',{name:'Multiplayer',exact:true}).click();await page.getByTestId('provider-race').waitFor();await settle();};
 const closeRace=async()=>{await page.getByRole('button',{name:'Return to puzzle',exact:true}).click();await page.getByTestId('provider-race').waitFor({state:'detached'});await settle();};
 const finish=async(expectedToken,label)=>{await metric(label+': retains the PIAN draft',await draft(),'PIAN');await metric(label+': retains the authoritative token',await token(),expectedToken);
  await page.keyboard.type('o');await page.getByRole('button',{name:/^submit$/i}).click();await page.waitForFunction(()=>window.probe.completions===1);
  await metric(label+': accepts one answer',await value('guesses'),1);await metric(label+': completes once',await value('completions'),1);
  await metric(label+': no browser errors',await value('windowErrors'),[]);await metric(label+': no unhandled promises',await value('unhandled'),[]);};

 await start('&reduced=1');const initialToken=await token();
 await metric('initial reduced motion schedules no decorative work',await idle(),0);
 await metric('initial reduced motion allocates no scene resources',await page.evaluate(()=>window.liveResources()),0);
 await motion(false,true);
 await metric('SDK preference update schedules scene without another gameplay action',await idle(),1);
 await metric('SDK preference read does not echo to provider persistence',await page.evaluate(()=>window.probe.preferenceWrites.filter(row=>'reducedMotion' in row)),[]);
 await motion(true);
 await metric('reduced motion cancels pending scene load',await idle(),0);
 await page.evaluate(()=>window.replayIdle());await settle();
 await metric('retained idle callback cannot mount reduced-motion scene',await page.locator('.solar-system canvas').count(),0);
 await motion(false);
 await page.evaluate(()=>{window.setMotion(true);window.releaseScene();});await settle();
 await metric('synchronous preference write blocks a callback before React commit',await page.locator('.solar-system canvas').count(),0);
 await finish(initialToken,'Initially reduced motion');

 await start();const deferredToken=await token();
 await metric('healthy initialized puzzle owns one deferred load',await idle(),1);
 await openRace();
 await metric('multiplayer cancels decoration that has not loaded',await idle(),0);
 await page.evaluate(()=>window.replayIdle());await settle();
 await metric('retained idle callback cannot mount behind multiplayer',await page.locator('.solar-system canvas').count(),0);
 await metric('multiplayer before deferred load owns no scene resources',await page.evaluate(()=>window.liveResources()),0);
 await closeRace();
 await metric('returning to puzzle schedules one deferred load',await idle(),1);
 await mount();
 await metric('returning from multiplayer constructs a healthy scene',await page.locator('.solar-system canvas').count(),1);
 const draws=await value('draws'),constructors=await value('rendererConstructions'),allocations=await page.evaluate(()=>window.liveResources());
 await openRace();
 await metric('loaded decoration has no frame chain behind multiplayer',await pending(),0);
 await page.evaluate(()=>{for(let frame=0;frame<180;frame++)window.step(1000/60);window.replayFrames();window.resizeScene(390,844);});
 await metric('loaded decoration draws nothing behind multiplayer',await value('draws'),draws);
 await metric('multiplayer retains healthy graphics resources',await page.evaluate(()=>window.liveResources()),allocations);
 await page.evaluate(()=>window.pause(true));await page.locator('.game-app.paused').waitFor();
 await closeRace();
 await metric('closing multiplayer preserves independent host pause',await pending(),0);
 await page.evaluate(()=>window.pause(false));await page.locator('.game-app.paused').waitFor({state:'detached'});await settle();
 await metric('host resume starts exactly one frame chain',await pending(),1);
 await metric('multiplayer transitions do not reconstruct the scene',await value('rendererConstructions'),constructors);
 await page.evaluate(()=>window.step());
 await metric('resumed puzzle draws once',await value('draws'),draws+1);
 await motion(true,true);
 await metric('live SDK reduced motion removes scene canvas',await page.locator('.solar-system canvas').count(),0);
 await metric('live reduced motion releases all scene allocations',await page.evaluate(()=>window.liveResources()),0);
 await metric('live reduced motion cancels scene frame chain',await pending(),0);
 const diagnostics=await page.evaluate(()=>window.probe.errors.length),disposed=await value('disposals');
 await page.evaluate(()=>{window.replayIdle();window.replayFrames();window.resizeScene(390,844,true);for(const row of window.probe.textureCallbacks)row.onError?.(Error('retained image failure'));});
 await metric('retained callbacks do not resurrect reduced-motion graphics',await pending(),0);
 await metric('retained callbacks do not repeat cleanup',await value('disposals'),disposed);
 await metric('retained callbacks do not create diagnostics',await page.evaluate(()=>window.probe.errors.length),diagnostics);
 await metric('platform motion updates remain read-only',await page.evaluate(()=>window.probe.preferenceWrites.filter(row=>'reducedMotion' in row)),[]);
 await motion(false,true);
 if(!baseline)await page.locator('.solar-system canvas').waitFor({state:'attached'});else await settle();await page.evaluate(()=>window.step());await settle();
 await metric('re-enabling motion constructs one active scene',await page.locator('.solar-system canvas').count(),1);
 await page.evaluate(width=>{window.resizeScene(width,844);window.step();},width);
 await metric('re-enabled scene has one frame chain',await pending(),1);
 await metric('resources are never disposed twice',await value('duplicateReleases'),0);
 if(!baseline)await page.screenshot({path:path.join(output,`motion-restored-${scheduler}-${width}.png`)});
 await finish(deferredToken,'Multiplayer and live motion transitions');
}
