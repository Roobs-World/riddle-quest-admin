import {createFacebookTournamentPresentation} from "../FacebookTournamentPresentation";
import type {FacebookInstantSdk, FacebookInstantTournament} from "../fbinstant";
import type {ListFacebookTournamentResponse, RecordFacebookTournamentRunResponse} from "@qwordly/core/race";
import {setLocale} from "../../play/i18n";

/** Official UTC window and identity-free best score, never supplied by a native payload. */
const fixture = () => {
  /** Exact UTC start. */
  const startsAtMs = Date.parse("2026-10-01T00:00:00Z");
  /** Current-player server standing. */
  const currentPlayer = {rank: 1, adjustedTimeMs: 9000, isCurrentPlayer: true};
  /** Exact authoritative board contract. */
  const board: ListFacebookTournamentResponse = {tournamentId: "facebook-race10-en-2026-10-01", locale: "en", startsAtMs,
    endsAtMs: startsAtMs + 86400000, sortOrder: "LOWER_IS_BETTER", rewardsEnabled: false, standings: [currentPlayer], currentPlayer};
  /** Bounded native hints generated by this game. */
  const data = {kind: "rq-race10-tournament-v1", locale: "en", tournamentId: board.tournamentId,
    startsAtMs: board.startsAtMs, endsAtMs: board.endsAtMs};
  /** SDK getters model untrusted current native state. */
  const native: FacebookInstantTournament = {getID: () => "native-1", getContextID: () => "context-1",
    getEndTime: () => board.endsAtMs / 1000, getPayload: () => data};
  /** Only real advertised Meta APIs are used by the adapter. */
  const sdk = {getSupportedAPIs: () => ["getTournamentAsync", "tournament.createAsync", "tournament.shareAsync", "tournament.postScoreAsync"],
    context: {getID: () => "context-1"}, getTournamentAsync: jest.fn(async () => native),
    tournament: {createAsync: jest.fn(async () => native), shareAsync: jest.fn(async () => undefined),
      postScoreAsync: jest.fn(async () => undefined)}} as unknown as FacebookInstantSdk;
  /** Server source and clock are injectable without weakening parsing. */
  const options = {sdk, enabled: true, ageCategory: "13_plus" as const, isActive: () => true, getLocale: () => "en" as const,
    list: jest.fn(async () => board), now: () => startsAtMs + 1000, renderImage: jest.fn(() => "data:image/png;base64,YQ=="), reportFailure: jest.fn()};
  /** Server-recorded completion, never a browser submission score. */
  const record: RecordFacebookTournamentRunResponse = {tournamentId: board.tournamentId, locale: "en", runId: "run-1",
    adjustedTimeMs: 10000, completedAtMs: startsAtMs + 500, improved: true, sortOrder: "LOWER_IS_BETTER", rewardsEnabled: false};
  return {options, sdk, board, native, data, record};
};

beforeEach(() => setLocale("en"));

it("projects an already-recorded official win after browser recovery", async () => {
  /** Synthetic provider fixtures preserve authoritative server and native SDK boundaries. */
  const {options, sdk, record} = fixture();
  await createFacebookTournamentPresentation(options)!.projectRecord({...record, improved: false});
  expect(sdk.tournament!.postScoreAsync).toHaveBeenCalledWith(9000);
});

it("creates one native dialog with the official current best, lower-time order and exact UTC deadline", async () => {
  /** Current entry has no native tournament. */
  const {options, sdk, board, data} = fixture();
  jest.mocked(sdk.getTournamentAsync!).mockRejectedValueOnce({code: "TOURNAMENT_NOT_FOUND"});
  await expect(createFacebookTournamentPresentation(options)!.share("en")).resolves.toMatchObject({status: "success"});
  expect(sdk.tournament!.createAsync).toHaveBeenCalledWith({initialScore: 9000,
    config: {title: "Tournaments", image: "data:image/png;base64,YQ==", sortOrder: "LOWER_IS_BETTER", scoreFormat: "NUMERIC",
      endTime: board.endsAtMs / 1000}, data});
  expect(sdk.tournament!.shareAsync).not.toHaveBeenCalled();
  expect(JSON.stringify(data).length).toBeLessThan(1000);
});

it("shares the matching current native tournament with v8 score/data only", async () => {
  /** Existing native context matches the exact server window. */
  const {options, sdk, data} = fixture();
  await expect(createFacebookTournamentPresentation(options)!.share("en")).resolves.toMatchObject({status: "success"});
  expect(sdk.tournament!.shareAsync).toHaveBeenCalledWith({score: 9000, data});
  expect(sdk.tournament!.createAsync).not.toHaveBeenCalled();
});

it("projects only a fresh authoritative best after an improved record and isolates provider failure", async () => {
  /** Best may improve again after this record, so the projection rereads the server. */
  const {options, sdk, record, board} = fixture();
  /** Provider projection remains separate from successful official submission. */
  const presentation = createFacebookTournamentPresentation(options)!;
  await presentation.projectRecord(record);
  expect(sdk.tournament!.postScoreAsync).toHaveBeenCalledWith(9000);
  board.currentPlayer!.adjustedTimeMs = 8000;
  jest.mocked(sdk.tournament!.postScoreAsync).mockRejectedValueOnce(new Error("private provider diagnostics"));
  await expect(presentation.projectRecord(record)).resolves.toBeUndefined();
  expect(options.reportFailure).toHaveBeenCalledWith(new Error("facebook-tournament-score-projection-failed"));
  await presentation.projectRecord({...record, improved: false});
  expect(sdk.tournament!.postScoreAsync).toHaveBeenCalledTimes(3);
  await presentation.projectRecord({...record, improved: false});
  expect(sdk.tournament!.postScoreAsync).toHaveBeenCalledTimes(3);
  board.currentPlayer!.adjustedTimeMs = 7000;
  options.reportFailure.mockImplementationOnce(() => {throw new Error("telemetry unavailable");});
  jest.mocked(sdk.tournament!.postScoreAsync).mockRejectedValueOnce(new Error("provider unavailable"));
  await expect(presentation.projectRecord(record)).resolves.toBeUndefined();
});

it.each(["USER_INPUT", "USER_CANCELLED"])("treats %s as cancellation and releases native dialog occupancy", async code => {
  /** A dismissed share remains retryable by the player. */
  const {options, sdk} = fixture();
  jest.mocked(sdk.tournament!.shareAsync).mockRejectedValueOnce({code});
  /** One SDK instance has one dialog coordinator. */
  const presentation = createFacebookTournamentPresentation(options)!;
  await expect(presentation.share("en")).resolves.toMatchObject({status: "cancelled"});
  await expect(presentation.share("en")).resolves.toMatchObject({status: "success"});
  expect(options.reportFailure).not.toHaveBeenCalled();
});

it("never creates a tournament after an ambiguous transport error and rejects foreign metadata", async () => {
  /** Unknown lookup failures cannot establish native tournament absence. */
  const {options, sdk, native, data, record} = fixture();
  /** One SDK instance is reused across guarded attempts. */
  const presentation = createFacebookTournamentPresentation(options)!;
  jest.mocked(sdk.getTournamentAsync!).mockRejectedValueOnce({code: "NETWORK_FAILURE"});
  await expect(presentation.share("en")).resolves.toMatchObject({status: "retryable-failure"});
  expect(sdk.tournament!.createAsync).not.toHaveBeenCalled();
  for (const payload of [{...data, locale: "fr"}, {...data, rewardsEnabled: true}, {...data, tournamentId: "foreign"}]) {
    native.getPayload = () => payload;
    await expect(presentation.share("en")).resolves.toMatchObject({status: "unavailable"});
    await presentation.projectRecord(record);
  }
  expect(sdk.tournament!.shareAsync).not.toHaveBeenCalled();
  expect(sdk.tournament!.postScoreAsync).not.toHaveBeenCalled();
});

it("guards duplicate dialogs and late account/locale changes while standings are pending", async () => {
  /** One pending server read owns the provider dialog slot. */
  const {options, sdk, board} = fixture();
  /** Resolve the controlled authenticated standings request. */
  let release!: (board: ListFacebookTournamentResponse) => void;
  options.list.mockImplementationOnce(() => new Promise(resolve => {release = resolve;}));
  /** Selected account lifetime may end while the read is in flight. */
  let active = true;
  options.isActive = () => active;
  /** Sharing acquires occupancy before a server read. */
  const presentation = createFacebookTournamentPresentation(options)!;
  /** Retain the exact live read handle. */
  const pending = presentation.share("en");
  await expect(presentation.share("en")).resolves.toMatchObject({status: "unavailable"});
  active = false;
  release(board);
  await expect(pending).resolves.toMatchObject({status: "unavailable"});
  expect(sdk.getTournamentAsync).not.toHaveBeenCalled();
  expect(sdk.tournament!.shareAsync).not.toHaveBeenCalled();
});

it("fails closed without SDK methods, authority, a live window or a current-player best", async () => {
  /** Full optional capability requires the independent gates. */
  const {options, sdk, board} = fixture();
  expect(createFacebookTournamentPresentation({...options, enabled: false})).toBeUndefined();
  expect(createFacebookTournamentPresentation({...options, ageCategory: "unknown"})).toBeUndefined();
  await expect(createFacebookTournamentPresentation({...options, now: () => board.endsAtMs})!.share("en")).resolves.toMatchObject({status: "unavailable"});
  options.list.mockResolvedValueOnce({...board, standings: [], currentPlayer: undefined});
  await expect(createFacebookTournamentPresentation(options)!.share("en")).resolves.toMatchObject({status: "unavailable"});
  sdk.getSupportedAPIs = () => [];
  expect(createFacebookTournamentPresentation(options)).toBeUndefined();
});

it("rejects a locale change or deadline crossing while the native lookup is pending", async () => {
  /** A provider lookup is owned by the original locale and UTC window. */
  const {options, sdk, native, board} = fixture();
  /** Resolve the exact pending SDK lookup instead of assuming its outcome. */
  let release!: (native: FacebookInstantTournament) => void;
  jest.mocked(sdk.getTournamentAsync!).mockImplementationOnce(() => new Promise(resolve => {release = resolve;}));
  /** Locale may change during an active account lifetime. */
  let sameLocale = true;
  /** Revalidate the host clock after provider work completes. */
  let clock = options.now();
  /** Production callbacks are reread instead of capturing a stale rendering value. */
  const presentation = createFacebookTournamentPresentation({...options, getLocale: () => sameLocale ? "en" : "fr", now: () => clock})!;
  /** This native operation is confirmed live before changing its inputs. */
  const pending = presentation.share("en");
  await Promise.resolve(); await Promise.resolve();
  sameLocale = false;
  clock = board.endsAtMs;
  release(native);
  await expect(pending).resolves.toMatchObject({status: "unavailable"});
  expect(sdk.tournament!.shareAsync).not.toHaveBeenCalled();
  expect(sdk.tournament!.createAsync).not.toHaveBeenCalled();
});

it("never posts a server best that contradicts the improved authoritative run", async () => {
  /** Native projection must fail closed on a structurally valid but inconsistent best score. */
  const {options, sdk, board, record} = fixture();
  /** The improved record is faster than this impossible later best. */
  const currentPlayer = {...board.currentPlayer!, adjustedTimeMs: record.adjustedTimeMs + 1000};
  options.list.mockResolvedValueOnce({...board, currentPlayer, standings: [currentPlayer]});
  await createFacebookTournamentPresentation(options)!.projectRecord(record);
  expect(sdk.getTournamentAsync).not.toHaveBeenCalled();
  expect(sdk.tournament!.postScoreAsync).not.toHaveBeenCalled();
});

it("deduplicates concurrent recovered boards and never posts an older slower best", async () => {
  /** Synthetic provider fixtures preserve authoritative server and native SDK boundaries. */
  const {options, sdk, board} = fixture();
  /** One SDK lifetime owns projection deduplication and provider failure isolation. */
  const presentation = createFacebookTournamentPresentation(options)!;
  await Promise.all(Array.from({length: 4}, () => presentation.projectBoard(board)));
  expect(sdk.tournament!.postScoreAsync).toHaveBeenCalledTimes(1);
  /** A newer official best arrives before an older slower snapshot. */
  const better = {...board, currentPlayer: {...board.currentPlayer!, adjustedTimeMs: 8000},
    standings: [{...board.standings[0], adjustedTimeMs: 8000}]};
  await Promise.all([presentation.projectBoard(better), presentation.projectBoard(board)]);
  expect(jest.mocked(sdk.tournament!.postScoreAsync!).mock.calls).toEqual([[9000], [8000]]);
});

it.each(["deletion", "locale"])("retires recovered projection after %s while provider lookup is pending", async ending => {
  /** Synthetic provider fixtures preserve authoritative server and native SDK boundaries. */
  const {options, sdk, board, native} = fixture();
  /** The fixture exposes the same changing deletion gate as the real adapter. */
  let active = true;
  /** Selected content locale is rechecked after provider work. */
  let locale: import("@qwordly/core/race").RaceLocale = "en";
  /** Controlled provider completion exercises retirement during an asynchronous lookup. */
  let resolve!: (native: FacebookInstantTournament) => void;
  jest.mocked(sdk.getTournamentAsync!).mockImplementationOnce(() => new Promise(yes => {resolve = yes;}));
  /** Owned asynchronous operation remains observable until it settles. */
  const pending = createFacebookTournamentPresentation({...options, isActive: () => active, getLocale: () => locale})!.projectBoard(board);
  await Promise.resolve();
  if (ending === "deletion") active = false;
  else locale = "fr";
  resolve(native);
  await pending;
  expect(sdk.tournament!.postScoreAsync).not.toHaveBeenCalled();
});
