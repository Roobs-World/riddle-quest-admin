import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {createHash} from 'node:crypto';
import {mkdir, readFile, readdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {developmentSourceDigest} from '../../../scripts/release/development-source-digest.mjs';
import {reuseDevelopmentChecks} from '../../../scripts/release/development-check-reuse.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const directory = path.join(root, 'artifacts/goal-completion-2026-10-24/riddle/manifest-evidence-audit');
await mkdir(directory, {recursive: true});
const execute = promisify(execFile);
const {stdout} = await execute('git', ['rev-parse', 'HEAD'], {cwd: root});
const revision = stdout.trim();
const sourceDigest = await developmentSourceDigest(root);
const union = JSON.parse(await readFile(path.join(root, 'artifacts/goal-completion-2026-10-24/riddle/manifest-check-union.json'), 'utf8'));
const hash = value => createHash('sha256').update(value).digest('hex');
const inputs = process.argv.slice(2);
if (!inputs.length) throw new Error('Pass check report paths explicitly');
const currentRows = new Map(), attempts = [], rejected = [];
for (const file of inputs) {
  const report = JSON.parse(await readFile(path.resolve(root, file), 'utf8'));
  for (const row of report.checks ?? []) {
    const before = row.sourceBefore ?? report.sourceDigest;
    const after = row.sourceAfter ?? report.sourceDigest;
    const key = JSON.stringify([row.executable, row.args]);
    const attempt = {report: file, index: row.index, executable: row.executable, args: row.args, status: row.status,
      checkedAt: row.checkedAt, revision: report.revision, sourceBefore: before, sourceAfter: after,
      log: row.log, sha256: row.sha256, ...(row.reason ? {reasonSummary: row.reason.split('\n')[0]} : {})};
    attempts.push(attempt);
    if (report.revision !== revision || before !== sourceDigest || after !== sourceDigest || row.sourceStillMatches === false) continue;
    if (!row.log || !row.sha256 || !row.executable || !Array.isArray(row.args)) {rejected.push({...attempt, reason: 'Incomplete command or log metadata'}); continue;}
    const log = path.resolve(root, row.log);
    if (!path.relative(root, log).startsWith(`artifacts${path.sep}development-checks${path.sep}`)) {rejected.push({...attempt, reason: 'Log is outside guarded evidence directory'}); continue;}
    try {
      if (hash(await readFile(log)) !== row.sha256) {rejected.push({...attempt, reason: 'Log digest mismatch'}); continue;}
    } catch (error) {rejected.push({...attempt, reason: `Log unavailable: ${error.message}`}); continue;}
    const previous = currentRows.get(key);
    if (!previous || Date.parse(row.checkedAt) > Date.parse(previous.checkedAt)) currentRows.set(key, {...row, originReport: file});
  }
}
const merged = {revision, sourceDigest, auditedAt: new Date().toISOString(), checks: [...currentRows.values()]};
const mergedFile = path.join(directory, `${sourceDigest}-checks.json`);
await writeFile(mergedFile, JSON.stringify(merged, null, 2) + '\n');
const snapshot = JSON.parse(await readFile(path.join(root, 'docs/reports/platform-release-readiness/src/data.json'), 'utf8'));
const historicalRows = snapshot.queries.development_progress?.rows ?? [];
const tasks = [];
const artifactProvenance = new Map();
let neutralRefresh;
try {neutralRefresh = JSON.parse(await readFile(path.join(root, 'artifacts/goal-completion-2026-10-24/riddle/neutral-handoffs/status.json'), 'utf8'));} catch (error) {if (error.code !== 'ENOENT') throw error;}
async function provenanceFor(file) {
  if (artifactProvenance.has(file)) return artifactProvenance.get(file);
  const sha256 = hash(await readFile(path.join(root, file)));
  let provenance;
  if (file === 'docs/evidence/platform-only-build-scope.md') {
    provenance = {file, sha256, kind: 'retained-source-document', regeneratedByVerification: false,
      note: 'This pre-existing source document is hashed as declared evidence. Running a check does not imply this document was regenerated.'};
  } else if (file === 'build-itch.zip' && neutralRefresh?.sourceBefore === sourceDigest && neutralRefresh?.sourceAfter === sourceDigest &&
    neutralRefresh.results?.some(row => row.artifact === file && row.sha256 === sha256 && row.status === 'passed')) {
    provenance = {file, sha256, kind: 'fresh-current-source-neutral-handoff', regeneratedByVerification: true,
      generationEvidence: 'artifacts/goal-completion-2026-10-24/riddle/neutral-handoffs/status.json',
      note: 'Generated by the separate canonical neutral handoff preparation, not by every command whose receipt observes this artifact.'};
  } else {
    const producers = file === 'artifacts/retained-creator-recovery-2026-10-10/browser.json' ? [178] :
      file === 'builds/reddit/index.html' || file === 'artifacts/target-dependencies/reddit.json' ? [7, 181] :
        file === 'build-gamesnacks.zip' || file.startsWith('builds/') || file.startsWith('artifacts/target-dependencies/') ? [7] : [];
    const rows = [...currentRows.values()].filter(row => producers.includes(row.index) && row.status === 'passed' && row.artifacts?.[file] === sha256);
    provenance = rows.length ? {file, sha256, kind: 'fresh-output-of-designated-current-command', regeneratedByVerification: true,
      generationEvidence: rows.map(row => ({index: row.index, log: row.log, sha256: row.sha256})),
      note: 'Fresh output belongs to the designated build or browser command. Other rows only observe and bind its bytes.'} :
      {file, sha256, kind: 'retained-artifact-without-current-generation-proof', regeneratedByVerification: false,
        note: 'The bytes are retained and hashed. No current producing command has yet been admitted, so regeneration is not claimed.'};
  }
  artifactProvenance.set(file, provenance);
  return provenance;
}
for (const name of (await readdir(path.join(root, 'docs/development-tasks'))).filter(name => name.endsWith('.json')).sort()) {
  const file = `docs/development-tasks/${name}`;
  const task = JSON.parse(await readFile(path.join(root, file), 'utf8'));
  let checks, error;
  try {checks = await reuseDevelopmentChecks(root, task, merged, {revision, sourceDigest});}
  catch (failure) {error = failure.message;}
  const conflicts = historicalRows.filter(row => row.taskId === task.taskId && row.revision === revision && row.sourceDigest !== sourceDigest);
  const artifactDeclarations = [];
  for (const artifact of task.artifacts ?? []) artifactDeclarations.push({file: artifact.file, checkId: artifact.checkId ?? null,
    binding: artifact.checkId ? 'named-check-binding' : 'unbound-retained-evidence-hash',
    generatedByEveryRequiredCheck: false, provenanceKind: (await provenanceFor(artifact.file)).kind});
  tasks.push({taskId: task.taskId, manifest: file, manifestSha256: hash(await readFile(path.join(root, file))), artifactDeclarations,
    status: error ? 'unverified' : 'verified-current-source', ...(error ? {reason: error} : {checks}),
    receiptPromotion: error ? 'not-eligible' : conflicts.length ? 'blocked-same-revision-different-source' : 'eligible',
    priorReceiptRows: conflicts.length});
}
const result = {revision, sourceDigest, auditedAt: new Date().toISOString(), exactCommands: merged.checks.length,
  scope: 'Exact local development-manifest checks. Hosted provider end-to-end evidence is recorded separately; provider publication is not implied.',
  requiredExactCommands: union.checks.length,
  missingExactCommandIndices: union.checks.flatMap((check, index) => currentRows.has(JSON.stringify([check.executable, check.args])) ? [] : [index]),
  failedExactCommands: merged.checks.filter(row => row.status !== 'passed').map(row => row.index),
  manifestCount: tasks.length, verifiedManifests: tasks.filter(task => task.status === 'verified-current-source').length,
  receiptPromotionBlocked: tasks.filter(task => task.receiptPromotion === 'blocked-same-revision-different-source').length,
  artifactProvenance: [...artifactProvenance.values()],
  currentSourceFailedAttempts: attempts.filter(attempt => attempt.revision === revision && attempt.sourceBefore === sourceDigest && attempt.sourceAfter === sourceDigest && attempt.status === 'failed'),
  historicalFailedAttempts: attempts.filter(attempt => attempt.status === 'failed' && (attempt.revision !== revision || attempt.sourceBefore !== sourceDigest || attempt.sourceAfter !== sourceDigest)),
  verificationLimitations: attempts.some(attempt => attempt.index === 84 && attempt.status === 'failed' && attempt.sourceBefore === '96e2b6b6f58b0e8a00d299435c643cc5a2fa034072e910213e9cf7a707a75402') ? [
    'On the prior c1224fc revision / 96e2b6b6 source, exact command 84 exceeded the existing 30-second per-test timeout in the subscription-refresh scenario. Its unchanged-source exact rerun completed in 28.796 seconds; the structured assertion report records 24.371 seconds for that scenario. The initial attempt has no action trace identifying a functional cause; retain this as an unresolved timing flake under concurrent verification. A later passing check does not prove harmless resource contention.',
  ] : [],
  artifactScope: 'Artifact hashes bind the declared bytes. An absent checkId is an unbound evidence declaration and never means that every required command regenerated that artifact or unrelated task screenshots and logs.',
  checksReport: path.relative(root, mergedFile), inputs, rejected, attempts, tasks};
const resultFile = path.join(directory, `${sourceDigest}-audit.json`);
await writeFile(resultFile, JSON.stringify(result, null, 2) + '\n');
if (await developmentSourceDigest(root) !== sourceDigest) throw new Error('Source changed during audit; preserve this audit as historical only');
console.log(JSON.stringify({sourceDigest, exactCommands: result.exactCommands, manifestCount: result.manifestCount,
  missingExactCommandIndices: result.missingExactCommandIndices,
  verifiedManifests: result.verifiedManifests, receiptPromotionBlocked: result.receiptPromotionBlocked,
  failedExactCommands: result.failedExactCommands, rejected: rejected.length, report: path.relative(root, resultFile)}));
if (result.verifiedManifests !== result.manifestCount || result.failedExactCommands.length || rejected.length) process.exitCode = 1;
