"use strict";

const fs = require("fs");
const path = require("path");

const {
  LOCALES,
  LANGUAGE_LABELS,
  NAMESPACE_TO_SECTIONS,
  ensureDir,
  flattenLeafPaths,
  getValueAtPath,
  isPlainObject,
  toTsObjectLiteral,
} = require("./i18n-shared");

const rootDir = path.resolve(__dirname, "..");
const localesDir = path.join(rootDir, "src", "locales");
const generatedDir = path.join(rootDir, "src", "i18n", "generated");

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function getLocaleNamespaceMap(locale) {
  const localeDir = path.join(localesDir, locale);
  const files = fs
    .readdirSync(localeDir)
    .filter((entry) => entry.endsWith(".json"))
    .sort((left, right) => left.localeCompare(right));

  return files.reduce((acc, entry) => {
    const namespace = path.basename(entry, ".json");
    acc[namespace] = readJson(path.join(localeDir, entry));
    return acc;
  }, {});
}

function validateLocaleNamespaces(englishNamespaces, localeNamespaces, locale) {
  const englishNamespaceNames = Object.keys(englishNamespaces).sort();
  const localeNamespaceNames = Object.keys(localeNamespaces).sort();

  if (JSON.stringify(englishNamespaceNames) !== JSON.stringify(localeNamespaceNames)) {
    throw new Error(`Namespace mismatch for ${locale}: expected ${englishNamespaceNames.join(", ")} got ${localeNamespaceNames.join(", ")}`);
  }
}

function validateLocaleShape(englishNamespaces, localeNamespaces, locale) {
  for (const namespace of Object.keys(englishNamespaces)) {
    const englishPaths = flattenLeafPaths(englishNamespaces[namespace]).sort();
    const localePaths = flattenLeafPaths(localeNamespaces[namespace]).sort();

    const missing = englishPaths.filter((entry) => !localePaths.includes(entry));
    const extra = localePaths.filter((entry) => !englishPaths.includes(entry));

    if (missing.length || extra.length) {
      throw new Error(
        [
          `Locale ${locale} namespace ${namespace} does not match English schema.`,
          missing.length ? `Missing: ${missing.join(", ")}` : null,
          extra.length ? `Extra: ${extra.join(", ")}` : null,
        ]
          .filter(Boolean)
          .join(" "),
      );
    }

    for (const leafPath of englishPaths) {
      const englishValue = getValueAtPath(englishNamespaces[namespace], leafPath);
      const localeValue = getValueAtPath(localeNamespaces[namespace], leafPath);

      if (typeof englishValue !== typeof localeValue) {
        throw new Error(
          `Locale ${locale} namespace ${namespace} has type mismatch at ${leafPath}: expected ${typeof englishValue}, got ${typeof localeValue}`,
        );
      }
    }
  }
}

function buildRootCatalog(localeNamespaces) {
  return Object.keys(NAMESPACE_TO_SECTIONS).reduce((acc, namespace) => {
    const sections = NAMESPACE_TO_SECTIONS[namespace];
    const namespaceValue = localeNamespaces[namespace];

    for (const section of sections) {
      acc[section] = namespaceValue[section];
    }

    return acc;
  }, {});
}

function buildKeyList(value, prefix = "") {
  if (!isPlainObject(value)) {
    return [prefix];
  }

  return Object.entries(value).flatMap(([key, child]) => {
    const nextPrefix = prefix ? `${prefix}.${key}` : key;
    return buildKeyList(child, nextPrefix);
  });
}

function writeTypesFile(englishRoot, namespaces) {
  const localeUnion = LOCALES.map((locale) => JSON.stringify(locale)).join(" | ");
  const namespaceUnion = namespaces.map((namespace) => JSON.stringify(namespace)).join(" | ");

  const content = `/**
 * @generated by scripts/generate-i18n.js
 * Do not edit this file directly.
 */

export const translationSchema = ${toTsObjectLiteral(englishRoot)} as const;

export type TranslationSchema = typeof translationSchema;
export type Locale = ${localeUnion};
export type Namespace = ${namespaceUnion};

export type DeepLeafKeys<T, Prefix extends string = ""> = T extends string
  ? Prefix
  : {
      [K in keyof T & string]: DeepLeafKeys<T[K], Prefix extends "" ? K : \`\${Prefix}.\${K}\`>;
    }[keyof T & string];

export type TranslationKey = DeepLeafKeys<TranslationSchema>;

export type LanguageOption = {
  code: Locale;
  label: string;
};
`;

  fs.writeFileSync(path.join(generatedDir, "types.ts"), content);
}

function writeKeysFile(englishRoot) {
  const keys = buildKeyList(englishRoot).sort();
  const content = `/**
 * @generated by scripts/generate-i18n.js
 * Do not edit this file directly.
 */

import type {TranslationKey} from "./types";

export const TRANSLATION_KEYS = ${toTsObjectLiteral(keys)} as const satisfies readonly TranslationKey[];
`;

  fs.writeFileSync(path.join(generatedDir, "keys.ts"), content);
}

function writeCatalogsFile(namespaces) {
  const importLines = [];
  const localeEntries = [];

  for (const locale of LOCALES) {
    const namespaceEntries = [];

    for (const namespace of namespaces) {
      const importName = `${locale}_${namespace}`.replace(/[^a-zA-Z0-9_]/g, "_");
      importLines.push(`import ${importName} from "../../locales/${locale}/${namespace}.json";`);
      namespaceEntries.push(`    ${JSON.stringify(namespace)}: ${importName}`);
    }

    localeEntries.push(`  ${JSON.stringify(locale)}: {\n${namespaceEntries.join(",\n")}\n  }`);
  }

  const languageOptions = LOCALES.map((locale) => `  {code: ${JSON.stringify(locale)}, label: ${JSON.stringify(LANGUAGE_LABELS[locale])}}`).join(",\n");

  const content = `/**
 * @generated by scripts/generate-i18n.js
 * Do not edit this file directly.
 */

${importLines.join("\n")}
import type {LanguageOption, Locale, Namespace} from "./types";

export const SUPPORTED_LOCALES = ${toTsObjectLiteral(LOCALES)} as const;

export const LANGUAGE_OPTIONS: readonly LanguageOption[] = [
${languageOptions}
] as const;

export const localeCatalogs: Record<Locale, Record<Namespace, unknown>> = {
${localeEntries.join(",\n")}
};
`;

  fs.writeFileSync(path.join(generatedDir, "catalogs.ts"), content);
}

function main() {
  ensureDir(generatedDir);

  const englishNamespaces = getLocaleNamespaceMap("en");
  const namespaceNames = Object.keys(englishNamespaces).sort();

  const localeRoots = {};

  for (const locale of LOCALES) {
    const localeNamespaces = getLocaleNamespaceMap(locale);
    validateLocaleNamespaces(englishNamespaces, localeNamespaces, locale);
    validateLocaleShape(englishNamespaces, localeNamespaces, locale);
    localeRoots[locale] = buildRootCatalog(localeNamespaces);
  }

  writeTypesFile(localeRoots.en, namespaceNames);
  writeKeysFile(localeRoots.en);
  writeCatalogsFile(namespaceNames);
}

main();
